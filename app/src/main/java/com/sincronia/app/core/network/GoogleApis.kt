package com.sincronia.app.core.network

import kotlinx.serialization.json.JsonObject
import retrofit2.Response
import retrofit2.http.Body
import retrofit2.http.DELETE
import retrofit2.http.GET
import retrofit2.http.PATCH
import retrofit2.http.POST
import retrofit2.http.Path
import retrofit2.http.Query

/** Calendar API v3, primary calendar only (no calendars.get nor calendarList: rule 4). */
interface CalendarApi {
    @GET("calendar/v3/calendars/primary/events")
    suspend fun events(
        @Query("timeMin") timeMin: String,
        @Query("timeMax") timeMax: String,
        @Query("pageToken") pageToken: String? = null,
        @Query("singleEvents") singleEvents: Boolean = true,
        @Query("maxResults") maxResults: Int = 250,
    ): EventListDto

    @GET("calendar/v3/calendars/primary/events/{id}")
    suspend fun event(@Path("id") id: String): EventDto

    /** The body carries the id generated by the app (spec 7.2.1). */
    @POST("calendar/v3/calendars/primary/events")
    suspend fun insert(@Body body: JsonObject): EventDto

    @PATCH("calendar/v3/calendars/primary/events/{id}")
    suspend fun patch(@Path("id") id: String, @Body body: JsonObject): EventDto

    @DELETE("calendar/v3/calendars/primary/events/{id}")
    suspend fun delete(@Path("id") id: String): Response<Unit>
}

/** Tasks API v1. The default page size is only 20, so maxResults is always sent. */
interface TasksApi {
    @GET("tasks/v1/users/@me/lists")
    suspend fun lists(@Query("pageToken") pageToken: String? = null, @Query("maxResults") maxResults: Int = 100): TaskListsDto

    @GET("tasks/v1/users/@me/lists/@default")
    suspend fun defaultList(): TaskListDto

    @GET("tasks/v1/lists/{listId}/tasks")
    suspend fun tasks(
        @Path("listId") listId: String,
        @Query("updatedMin") updatedMin: String? = null,
        @Query("pageToken") pageToken: String? = null,
        @Query("maxResults") maxResults: Int = 100,
        @Query("showCompleted") showCompleted: Boolean = true,
        @Query("showHidden") showHidden: Boolean = true,
        @Query("showDeleted") showDeleted: Boolean = true,
    ): TasksDto

    @GET("tasks/v1/lists/{listId}/tasks/{id}")
    suspend fun task(@Path("listId") listId: String, @Path("id") id: String): TaskDto

    @POST("tasks/v1/lists/{listId}/tasks")
    suspend fun insert(@Path("listId") listId: String, @Body body: JsonObject): TaskDto

    @PATCH("tasks/v1/lists/{listId}/tasks/{id}")
    suspend fun patch(@Path("listId") listId: String, @Path("id") id: String, @Body body: JsonObject): TaskDto

    @DELETE("tasks/v1/lists/{listId}/tasks/{id}")
    suspend fun delete(@Path("listId") listId: String, @Path("id") id: String): Response<Unit>

    /** PATCH cannot change the list; move first (spec 7.2.1). */
    @POST("tasks/v1/lists/{listId}/tasks/{id}/move")
    suspend fun move(
        @Path("listId") listId: String,
        @Path("id") id: String,
        @Query("destinationTasklist") destination: String,
    ): TaskDto
}
