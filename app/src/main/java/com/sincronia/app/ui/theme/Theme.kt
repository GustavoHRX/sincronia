// Cores dinâmicas (Android 12+) ficam desligadas: elas trocariam a paleta azul
// pelas cores do papel de parede (seção 9).
@Composable
fun SincronIATheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    MaterialTheme(
        colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme,
        typography = Typography,
        shapes = Shapes,
        content = content
    )
}
